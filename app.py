def transaction_analysis() -> None:
    app_header("INVESTIGATION", "Transaction explorer", "Inspect a real node, its provenance, and its local graph context.")
    data = load_graph()
    from src.data_utils import node_degrees

    ids = np.asarray(data.tx_id).astype(str)
    if "selected_tx" not in st.session_state:
        st.session_state.selected_tx = ids[0]
    controls = st.columns([3, 1, 1])
    with controls[0]:
        query = st.text_input("Transaction ID", value=st.session_state.selected_tx, placeholder="Paste an exact txId…", help="Search is exact and uses IDs from the processed Elliptic graph.")
    with controls[1]:
        if st.button("Random node", use_container_width=True, help="Select a real transaction from the processed graph."):
            st.session_state.selected_tx = str(np.random.default_rng().choice(ids))
            st.rerun()
    with controls[2]:
        if st.button("Clear", use_container_width=True, help="Clear the search field."):
            st.session_state.selected_tx = ""
            st.rerun()
    matches = np.flatnonzero(ids == query.strip())
    if not len(matches):
        st.warning("No exact transaction ID found in the processed graph.")
        return
    idx = int(matches[0]); st.session_state.selected_tx = ids[idx]
    degree = int(node_degrees(data.edge_index, data.x.shape[0])[idx])
    label = {1: "Illicit", 0: "Licit", -1: "Unknown"}[int(data.y[idx])]
    cols = st.columns(4)
    for col, name, value in zip(cols, ["Transaction", "Timestep", "Label", "Undirected degree"], [ids[idx], str(int(data.timestep[idx])), label, str(degree)]):
        with col: metric_card(name, value, "Repository data")
    st.markdown("#### Model signal")
    pred_path = artifact("taf_gnn_predictions.csv")
    if pred_path.exists():
        pred = load_result("taf_gnn_predictions.csv")
        candidate = pred[pred.astype(str).apply(lambda col: col.eq(ids[idx])).any(axis=1)] if pred is not None else pd.DataFrame()
        if not candidate.empty:
            st.dataframe(candidate, use_container_width=True, hide_index=True)
        else:
            empty_state("No saved prediction for this transaction", "The TAF-GNN artifact exists, but does not contain this txId.")
    else:
        empty_state("Prediction unavailable", "No TAF-GNN prediction artifact is present. This panel will populate after the research runner completes.", "python -m src.run_experiments --data-root data/elliptic --output-root results")
    st.markdown("#### Feature statistics")
    vector = data.x[idx].numpy()
    feature_cols = st.columns(4)
    for col, name, value in zip(feature_cols, ["Mean", "Std dev", "Minimum", "Maximum"], [vector.mean(), vector.std(), vector.min(), vector.max()]):
        with col:
            metric_card(name, f"{value:.4f}", "Selected transaction")
    features = pd.DataFrame({"Feature": data.feature_names, "Value": vector})
    features["Absolute value"] = features["Value"].abs()
    st.dataframe(features.sort_values("Absolute value", ascending=False).drop(columns="Absolute value").head(30), use_container_width=True, height=260)
    st.markdown("#### One-hop graph context")
    src, dst = data.edge_index
    neighbor_mask = (src == idx) | (dst == idx)
    neighbors = np.unique(
        np.concatenate(
            [src[neighbor_mask].numpy(), dst[neighbor_mask].numpy()]
        )
    )
    neighbors = neighbors[neighbors != idx][:30]
    st.caption(f"Showing up to 30 of {int(neighbor_mask.sum())} incident edge records.")
    if len(neighbors):
        st.dataframe(
            pd.DataFrame(
                {
                    "txId": ids[neighbors],
                    "timestep": data.timestep[neighbors].numpy(),
                    "label": [
                        {1: "Illicit", 0: "Licit", -1: "Unknown"}[int(data.y[i])]
                        for i in neighbors
                    ],
                }
            ),
            use_container_width=True,
            hide_index=True,
        )


def graph_explorer() -> None:
    app_header("NETWORK", "Graph explorer", "Keep the browser responsive by rendering a bounded neighborhood only.")
    data = load_graph()
    from src.data_utils import node_degrees
    ids = np.asarray(data.tx_id).astype(str)
    selected = st.session_state.get("selected_tx", ids[0])
    if selected not in set(ids):
        selected = ids[0]
    idx = int(np.flatnonzero(ids == selected)[0])
    radius = st.slider("Visible neighbors", 5, 50, 20, help="Limit the local graph to keep the interactive view readable.")
    st.caption("The selected transaction is highlighted in the network. Colors represent repository labels; unknown labels are not predictions.")
    src, dst = data.edge_index
    incident_mask = (src == idx) | (dst == idx)
    incident = np.concatenate([src[incident_mask].numpy(), dst[incident_mask].numpy()])
    nodes = np.unique(np.concatenate([[idx], incident]))[: radius + 1]
    node_set = set(nodes.tolist())
    edge_pairs = [(int(a), int(b)) for a, b in zip(src[incident_mask].numpy(), dst[incident_mask].numpy()) if int(a) in node_set and int(b) in node_set]
    graph = nx.Graph()
    graph.add_nodes_from(nodes.tolist())
    graph.add_edges_from(edge_pairs)
    positions = nx.spring_layout(graph, seed=7)
    st.metric("Visible nodes", len(nodes), f"{len(edge_pairs)} local edges")
    labels = {1: "Illicit", 0: "Licit", -1: "Unknown"}
    node_df = pd.DataFrame({"txId": ids[nodes], "timestep": data.timestep[nodes].numpy(), "label": [labels[int(v)] for v in data.y[nodes]], "degree": node_degrees(data.edge_index, data.x.shape[0])[nodes].numpy()})
    st.dataframe(node_df, use_container_width=True, hide_index=True)
    labels = {1: "Illicit", 0: "Licit", -1: "Unknown"}
    edge_x, edge_y = [], []
    for a, b in graph.edges():
        edge_x += [positions[a][0], positions[b][0], None]
        edge_y += [positions[a][1], positions[b][1], None]
    fig = go.Figure(go.Scatter(x=edge_x, y=edge_y, mode="lines", line=dict(width=1, color="#38516b"), hoverinfo="none"))
    palette = {"Illicit": "#ff6b7a", "Licit": "#63e6be", "Unknown": "#71809b"}
    for label_name in ["Unknown", "Licit", "Illicit"]:
        members = [n for n in nodes if labels[int(data.y[n])] == label_name]
        if not members:
            continue
        fig.add_trace(go.Scatter(
            x=[positions[n][0] for n in members], y=[positions[n][1] for n in members],
            mode="markers", name=label_name,
            marker=dict(size=[13 if n == idx else 9 for n in members], color=palette[label_name], line=dict(width=1, color="#08101d")),
            text=[ids[n] for n in members],
            customdata=np.column_stack([data.timestep[members].numpy(), node_degrees(data.edge_index, data.x.shape[0])[members].numpy()]),
            hovertemplate="txId=%{text}<br>timestep=%{customdata[0]}<br>degree=%{customdata[1]}<extra>" + label_name + "</extra>",
        ))
    fig.update_layout(template="plotly_dark", height=480, showlegend=True, xaxis=dict(visible=False), yaxis=dict(visible=False), margin=dict(l=0,r=0,t=10,b=0))
    st.plotly_chart(fig, use_container_width=True)


