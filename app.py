@st.cache_resource(show_spinner="Loading the processed Elliptic graph…")
def load_graph() -> Any:
    from src.data_utils import load_elliptic

    return load_elliptic(ROOT / "data" / "elliptic")


@st.cache_data
def graph_summary() -> dict[str, Any]:
    data = load_graph()
    from src.data_utils import node_degrees

    degree = node_degrees(data.edge_index, data.x.shape[0])
    labeled = data.y[data.labeled_mask]
    return {
        "nodes": int(data.x.shape[0]),
        "edges": int(data.edge_index.shape[1]),
        "features": int(data.x.shape[1]),
        "timesteps": int(data.timestep.max()),
        "labeled": int(data.labeled_mask.sum()),
        "illicit": int((labeled == 1).sum()),
        "licit": int((labeled == 0).sum()),
        "degree": degree,
    }


@st.cache_data
def temporal_table() -> pd.DataFrame:
    data = load_graph()
    labels = data.y.numpy()
    steps = data.timestep.numpy()
    rows = []
    for step in sorted(np.unique(steps)):
        mask = steps == step
        labeled = mask & (labels >= 0)
        illicit = mask & (labels == 1)
        rows.append(
            {
                "Timestep": int(step),
                "Transactions": int(mask.sum()),
                "Labeled": int(labeled.sum()),
                "Illicit": int(illicit.sum()),
                "Illicit rate": float(illicit.sum() / labeled.sum()) if labeled.sum() else np.nan,
            }
        )
    return pd.DataFrame(rows)


